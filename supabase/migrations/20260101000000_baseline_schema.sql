-- BASELINE: the database exactly as it stood before we started keeping migration history
-- (snapshot taken from the live database on 2026-10-19, minus the later pin_hardening migration).
--
-- The production database already has all of this. It is recorded as "applied" there and is never
-- re-run; it exists so a brand-new project (or a local test copy) can be rebuilt from the repo:
-- baseline first, then every later migration in filename order. Everything uses IF NOT EXISTS
-- so running it by accident against a populated database changes nothing.
--
-- Row-level security (RLS) state at snapshot time: ON for plumbers and materials_entries (no policies);
-- OFF for the other nine tables. Step 7 turns it on for those nine (see later migrations).

create table if not exists plumbers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  pin text not null,
  role text default 'plumber',
  created_at timestamp without time zone default now()
);

create table if not exists vehicles (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  year text,
  make text,
  model text,
  current_mileage integer default 0,
  assigned_driver text,
  created_at timestamp without time zone default now()
);

create table if not exists conversations (
  id uuid primary key default gen_random_uuid(),
  plumber_id uuid references plumbers(id),
  role text not null,
  content text not null,
  channel text default 'assistant',
  created_at timestamp without time zone default now(),
  image_url text
);

create table if not exists shop_updates (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  content text not null,
  posted_by text not null,
  created_at timestamp without time zone default now()
);

create table if not exists shop_tools (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text default 'General',
  checked_out_by text,
  checked_out_at timestamp without time zone,
  notes text
);

create table if not exists training_tips (
  id uuid primary key default gen_random_uuid(),
  tip text not null,
  created_at timestamp without time zone default now(),
  tip_date date default current_date
);

create table if not exists quiz_questions (
  id uuid primary key default gen_random_uuid(),
  level text not null,
  topic text not null,
  question text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text not null,
  correct_answer text not null,
  explanation text not null
);

create table if not exists quiz_results (
  id uuid primary key default gen_random_uuid(),
  plumber_id uuid references plumbers(id),
  level text not null,
  topic text not null,
  score integer not null,
  total integer not null,
  created_at timestamp without time zone default now()
);

create table if not exists vehicle_service_log (
  id uuid primary key default gen_random_uuid(),
  vehicle_id uuid references vehicles(id),
  service_type text not null,
  mileage_at_service integer not null,
  notes text,
  logged_by text not null,
  created_at timestamp without time zone default now()
);

create table if not exists vehicle_issues (
  id uuid primary key default gen_random_uuid(),
  vehicle_id uuid references vehicles(id),
  description text not null,
  reported_by text not null,
  status text default 'open',
  created_at timestamp without time zone default now()
);

-- Each plumber's receipts for the week (My Pay). plumber_id is text here, unlike the uuid used elsewhere.
create table if not exists materials_entries (
  id bigint generated by default as identity primary key,
  plumber_id text not null,
  week_start date not null,
  amount numeric not null,
  created_at timestamp with time zone not null default now()
);
create index if not exists materials_entries_plumber_week_idx on materials_entries (plumber_id, week_start);

-- Locked down: security on, no policies, so only the server (service-role key) can read or write.
alter table plumbers enable row level security;
alter table materials_entries enable row level security;

-- Chat photo storage. Public bucket so photo links open for the AI and in the chat.
-- NOTE: three anonymous policies exist at snapshot time, including TWO duplicate upload policies.
-- That is a known problem; Step 7 removes the upload policies (the browser no longer uploads directly).
insert into storage.buckets (id, name, public)
values ('chat-images', 'chat-images', true)
on conflict (id) do nothing;

drop policy if exists "Anon can read chat images" on storage.objects;
create policy "Anon can read chat images" on storage.objects
  for select to anon using (bucket_id = 'chat-images');

drop policy if exists "Anon can upload chat images" on storage.objects;
create policy "Anon can upload chat images" on storage.objects
  for insert to anon with check (bucket_id = 'chat-images');

drop policy if exists "Anon upload chat images" on storage.objects;
create policy "Anon upload chat images" on storage.objects
  for insert to anon with check (bucket_id = 'chat-images');
