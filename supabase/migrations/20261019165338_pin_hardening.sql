-- Step 5: PIN hardening.
-- * plumbers gets pin_hash + pin_salt (the PIN is stored as a salted, peppered hash, never as typed).
-- * the old plain-text `pin` column becomes optional; the app blanks it as each person logs in,
--   and we drop it once everyone has been upgraded.
-- * login_attempts records tries so the server can lock out repeated wrong guesses.
--   Row-level security is ON with no policies: only the server (service role) can touch it.

alter table public.plumbers
  add column if not exists pin_hash text,
  add column if not exists pin_salt text;

alter table public.plumbers alter column pin drop not null;

create table if not exists public.login_attempts (
  id bigint generated by default as identity primary key,
  name text not null,
  ip text,
  success boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists login_attempts_name_idx on public.login_attempts (name, created_at desc);
create index if not exists login_attempts_ip_idx on public.login_attempts (ip, created_at desc);

alter table public.login_attempts enable row level security;
